export function getMaterialBySlug(slug: string): Material | undefined {
  return materials.find((m) => m.slug === slug);
}

export function getRelatedMaterials(material: Material, limit = 4): Material[] {
  return materials
    .filter((m) => m.id !== material.id)
    .sort((a, b) => {
      let aScore = 0;
      let bScore = 0;
      if (a.colour === material.colour) aScore += 3;
      if (b.colour === material.colour) bScore += 3;
      if (a.category === material.category) aScore += 2;
      if (b.category === material.category) bScore += 2;
      return bScore - aScore;
    })
    .slice(0, limit);
}
